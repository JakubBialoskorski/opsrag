import hashlib
import json
import time
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path

import httpx
import yaml

from opsrag.config import Settings

EMBED_BATCH = 32
REGISTRY = "https://registry.ollama.ai/v2"
MANIFEST_TYPE = "application/vnd.docker.distribution.manifest.v2+json"


class OllamaError(RuntimeError):
    pass


def full_name(model: str) -> str:
    """Ollama treats "nomic-embed-text" and "nomic-embed-text:latest" as the same model."""
    return model if ":" in model else f"{model}:latest"


@dataclass
class ModelInfo:
    digest: str
    params: str  # e.g. "4.0B"
    quantization: str  # e.g. "Q4_K_M"
    size: int  # bytes

    def describe(self) -> str:
        return f"{self.digest[:12]}  {self.params} {self.quantization}  {self.size / 1e9:.1f} GB"


def remote_model(model: str) -> ModelInfo:
    """What the Ollama registry currently serves under this name, without downloading it.
    Ollama's digest of a model is the sha256 of its manifest."""
    name, tag = full_name(model).split(":", 1)
    repo = name if "/" in name else f"library/{name}"
    try:
        response = httpx.get(
            f"{REGISTRY}/{repo}/manifests/{tag}", headers={"Accept": MANIFEST_TYPE}, timeout=15
        )
        response.raise_for_status()
        manifest = response.json()
        config = httpx.get(
            f"{REGISTRY}/{repo}/blobs/{manifest['config']['digest']}",
            follow_redirects=True,
            timeout=15,
        ).json()
    except httpx.HTTPError as e:
        raise OllamaError(f"can't look up {model} in the Ollama registry: {e}") from e
    return ModelInfo(
        digest=hashlib.sha256(response.content).hexdigest(),
        params=config.get("model_type", "?"),
        quantization=config.get("file_type", "?"),
        size=sum(layer["size"] for layer in manifest["layers"]),
    )


def load_model_lock(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    return yaml.safe_load(path.read_text()) or {}


def save_model_lock(path: Path, digests: dict[str, str]) -> None:
    header = (
        "# Generated by `make update-models`. A model name can be re-published with\n"
        "# different weights, the digest makes sure we run the model we tested.\n"
    )
    path.write_text(header + yaml.safe_dump(dict(sorted(digests.items()))))


def models_to_pull(
    models: list[str],
    installed: dict[str, str],
    lock: dict[str, str],
    registry_digest: Callable[[str], str],
) -> list[tuple[str, str]]:
    """[(model, why)] to download: missing ones, and outdated ones when the registry serves
    exactly the version in the lock (a model can't be pulled by digest, only by name)."""
    pulls = []
    for model in models:
        if model not in installed:
            pulls.append((model, "not installed"))
        elif (
            model in lock
            and installed[model] != lock[model]
            and registry_digest(model) == lock[model]
        ):
            pulls.append((model, "switching to the version in models.lock.yaml"))
    return pulls


def lock_problems(lock: dict[str, str], installed: dict[str, str], models: list[str]) -> list[str]:
    problems = []
    for model in models:
        if model in lock and installed.get(model) != lock[model]:
            got = installed.get(model, "not installed")[:12]
            problems.append(f"{model} is {got}, models.lock.yaml expects {lock[model][:12]}")
    return problems


class Ollama:
    def __init__(self, url: str, embed_model: str, chat_model: str, num_ctx: int):
        self.embed_model = embed_model
        self.chat_model = chat_model
        self.num_ctx = num_ctx
        # Generous read timeout: the first request loads the model into memory
        self.http = httpx.Client(base_url=url, timeout=httpx.Timeout(10, read=300))

    @classmethod
    def from_settings(cls, settings: Settings) -> "Ollama":
        return cls(settings.ollama_url, settings.embed_model, settings.chat_model, settings.num_ctx)

    def _post(self, path: str, payload: dict, retries: int = 3) -> dict:
        for attempt in range(1, retries + 1):
            try:
                response = self.http.post(path, json=payload)
                response.raise_for_status()
                return response.json()
            except httpx.TransportError as e:
                if attempt == retries:
                    raise OllamaError(f"Ollama is not reachable at {self.http.base_url}") from e
                time.sleep(2**attempt)
            except httpx.HTTPStatusError as e:
                raise OllamaError(f"{path} failed: {e.response.text}") from e
        raise AssertionError("unreachable")

    @property
    def models(self) -> list[str]:
        return [full_name(self.embed_model), full_name(self.chat_model)]

    def local_models(self) -> dict[str, ModelInfo]:
        return {
            m["name"]: ModelInfo(
                digest=m["digest"],
                params=m["details"].get("parameter_size", "?"),
                quantization=m["details"].get("quantization_level", "?"),
                size=m["size"],
            )
            for m in self._get("/api/tags")["models"]
        }

    def installed(self) -> dict[str, str]:
        """{model name: digest} of the models Ollama has locally."""
        return {name: info.digest for name, info in self.local_models().items()}

    def missing_models(self) -> list[str]:
        installed = self.installed()
        return [m for m in self.models if m not in installed]

    def pull(self, model: str) -> Iterator[str]:
        """Download a model, yielding short progress lines."""
        last = ""
        try:
            # Downloads take minutes, so no read timeout here
            with self.http.stream(
                "POST", "/api/pull", json={"model": model}, timeout=httpx.Timeout(10, read=None)
            ) as response:
                for line in response.iter_lines():
                    data = json.loads(line)
                    if "error" in data:
                        raise OllamaError(f"pulling {model} failed: {data['error']}")
                    status = data.get("status", "")
                    if data.get("total"):
                        percent = 100 * data.get("completed", 0) // data["total"]
                        status = f"downloading {model}: {percent // 10 * 10}%"
                    if status != last:
                        last = status
                        yield status
        except httpx.HTTPError as e:
            raise OllamaError(f"pulling {model} failed: {e}") from e

    def _get(self, path: str) -> dict:
        try:
            response = self.http.get(path, timeout=5)
            response.raise_for_status()
            return response.json()
        except httpx.HTTPError as e:
            raise OllamaError(f"Ollama is not reachable at {self.http.base_url}") from e

    def embed(self, texts: list[str]) -> list[list[float]]:
        vectors = []
        for i in range(0, len(texts), EMBED_BATCH):
            batch = texts[i : i + EMBED_BATCH]
            data = self._post("/api/embed", {"model": self.embed_model, "input": batch})
            vectors.extend(data["embeddings"])
        return vectors

    def chat_stream(self, messages: list[dict]) -> Iterator[str]:
        payload = {
            "model": self.chat_model,
            "messages": messages,
            "stream": True,
            # Skip the "reasoning" phase of models like qwen3, it's slow on a laptop
            "think": False,
            # num_predict caps the answer length so it always fits in the context window,
            # a fixed seed makes answers repeatable, which keeps the CI checks stable
            "options": {
                "num_ctx": self.num_ctx,
                "num_predict": 512,
                "temperature": 0.1,
                "seed": 42,
            },
        }
        try:
            with self.http.stream("POST", "/api/chat", json=payload) as response:
                if response.status_code != 200:
                    response.read()
                    raise OllamaError(f"/api/chat failed: {response.text}")
                for line in response.iter_lines():
                    if not line:
                        continue
                    data = json.loads(line)
                    if "error" in data:
                        raise OllamaError(data["error"])
                    yield data.get("message", {}).get("content", "")
        except httpx.TransportError as e:
            raise OllamaError(f"Ollama is not reachable at {self.http.base_url}") from e
