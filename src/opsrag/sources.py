import hashlib
import re
import string
import subprocess
from collections.abc import Iterator
from dataclasses import dataclass, field
from fnmatch import fnmatch
from pathlib import Path

import yaml

from opsrag.chunking import clean_markdown, explicit_heading_ids, split_front_matter

DOC_EXTENSIONS = {".md", ".mdx"}
INDEX_NAMES = {"_index", "index"}


@dataclass
class Source:
    name: str
    repo: str
    track: str  # branch name (e.g. "main") or tag pattern (e.g. "tags/v3.*")
    root: str  # docs directory inside the repo
    url: str  # template with {path}, e.g. https://kubernetes.io/docs/{path}/
    exclude: list[str] = field(default_factory=list)
    # Exceptions to `url`: [{"match": glob, "url": template using front matter fields}]
    links: list[dict] = field(default_factory=list)
    # How the docs site turns headings into #section ids: "github" or "blackfriday" (Hugo)
    anchors: str = "github"


@dataclass
class Document:
    source: str
    path: str  # relative to the source root
    url: str
    title: str
    body: str
    heading_ids: dict[str, list[str | None]] = field(default_factory=dict)  # explicit {#id}s

    @property
    def content_hash(self) -> str:
        return hashlib.sha256(f"{self.title}\n{self.body}".encode()).hexdigest()


@dataclass
class Locked:
    ref: str  # what gets fetched: a commit SHA (for branches) or a tag name
    version: str  # human readable, e.g. "v3.9.1" or "main@6b27bae"


def load_sources(path: Path) -> list[Source]:
    data = yaml.safe_load(path.read_text())
    return [Source(**item) for item in data["sources"]]


def lock_path(sources_file: Path) -> Path:
    return sources_file.with_name(sources_file.stem + ".lock.yaml")


def load_lock(sources_file: Path) -> dict[str, Locked]:
    path = lock_path(sources_file)
    if not path.exists():
        return {}
    data = yaml.safe_load(path.read_text()) or {}
    return {name: Locked(**entry) for name, entry in data.items()}


def save_lock(sources_file: Path, lock: dict[str, Locked]) -> None:
    data = {name: {"ref": e.ref, "version": e.version} for name, e in sorted(lock.items())}
    header = "# Generated by `opsrag update`, do not edit by hand.\n"
    lock_path(sources_file).write_text(header + yaml.safe_dump(data, sort_keys=False))


def _git(*args: str, cwd: Path | None = None) -> str:
    result = subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True)
    return result.stdout.strip()


def _version_key(tag: str) -> tuple[int, ...]:
    return tuple(int(n) for n in re.findall(r"\d+", tag))


def pick_latest_tag(tags: list[str]) -> str | None:
    """Highest version tag, ignoring pre-releases like v3.9.0-rc.0."""
    stable = [t for t in tags if "-" not in t]
    return max(stable, key=_version_key, default=None)


def resolve(source: Source) -> Locked:
    """Find the newest commit/tag for what the source tracks, using `git ls-remote`."""
    if source.track.startswith("tags/"):
        pattern = source.track.removeprefix("tags/")
        out = _git("ls-remote", "--tags", "--refs", source.repo, pattern)
        tags = [line.split("refs/tags/", 1)[1] for line in out.splitlines()]
        tag = pick_latest_tag(tags)
        if tag is None:
            raise ValueError(f"{source.name}: no stable tag matches {pattern!r}")
        return Locked(ref=tag, version=tag)
    out = _git("ls-remote", "--heads", source.repo, source.track)
    if not out:
        raise ValueError(f"{source.name}: branch {source.track!r} not found")
    sha = out.split()[0]
    return Locked(ref=sha, version=f"{source.track}@{sha[:7]}")


def sync(source: Source, locked: Locked, data_dir: Path) -> Path:
    """Shallow, sparse checkout of just the docs directory at the locked ref."""
    checkout = data_dir / source.name
    if not (checkout / ".git").exists():
        checkout.mkdir(parents=True, exist_ok=True)
        _git("init", "-q", cwd=checkout)
        _git("remote", "add", "origin", source.repo, cwd=checkout)
    _git("sparse-checkout", "set", "--no-cone", f"/{source.root.strip('/')}/", cwd=checkout)
    _git("fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", locked.ref, cwd=checkout)
    _git("checkout", "-q", "--force", "FETCH_HEAD", cwd=checkout)
    return checkout


def _link_rule_url(source: Source, rel_path: str, meta: dict) -> str | None:
    for rule in source.links:
        if not fnmatch(rel_path, rule["match"]):
            continue
        fields = [name for _, name, _, _ in string.Formatter().parse(rule["url"]) if name]
        # Fall back to the default URL when the page lacks a field, e.g. the glossary index
        if all(meta.get(name) for name in fields):
            return rule["url"].format_map(meta)
    return None


def doc_url(source: Source, rel_path: str, meta: dict | None = None) -> str:
    if url := _link_rule_url(source, rel_path, meta or {}):
        return url
    path = Path(rel_path).with_suffix("")
    if path.name in INDEX_NAMES:
        path = path.parent
    url = source.url.format(path="" if str(path) == "." else path.as_posix())
    return re.sub(r"(?<!:)/{2,}", "/", url)


def with_anchor(url: str, anchor: str | None) -> str:
    """Page URL plus the #section of a chunk, unless the URL already points somewhere on the page
    (glossary entries)."""
    return f"{url}#{anchor}" if anchor and "#" not in url else url


def is_excluded(source: Source, rel_path: str) -> bool:
    name = Path(rel_path).name
    # Files starting with "_" are partials included by other pages (except Hugo's _index.md)
    if name.startswith("_") and Path(name).stem != "_index":
        return True
    return any(fnmatch(rel_path, pattern) for pattern in source.exclude)


def is_published(meta: dict) -> bool:
    """Hugo snippets marked headless are only included into other pages, they have no URL."""
    build = meta.get("_build")
    return not meta.get("headless") and not (
        isinstance(build, dict) and build.get("render") == "never"
    )


def iter_documents(source: Source, checkout: Path) -> Iterator[Document]:
    root = checkout / source.root
    for file in sorted(root.rglob("*")):
        if file.suffix not in DOC_EXTENSIONS or not file.is_file():
            continue
        rel_path = file.relative_to(root).as_posix()
        if is_excluded(source, rel_path):
            continue
        meta, body = split_front_matter(file.read_text(encoding="utf-8", errors="replace"))
        if not is_published(meta):
            continue
        title = str(meta.get("title") or file.stem.replace("_", " ").replace("-", " "))
        yield Document(
            source=source.name,
            path=rel_path,
            url=doc_url(source, rel_path, meta),
            title=title,
            body=clean_markdown(body),
            heading_ids=explicit_heading_ids(body),
        )
